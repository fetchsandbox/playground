#!/usr/bin/env node
// Renders verify/RESULTS.md from verify/receipts/*.json and the contracts.
//   node verify/results.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
// Every workflow that has a receipt; RESULTS.md is generated locally, not committed.
const WORKFLOWS = readdirSync(join(HERE, "receipts")).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
const ICON = { held: "✅ held", violated: "❌ violated", unmeasured: "⏸ unmeasured" };

const out = [
  "# Relay proof results",
  "",
  "Generated by `node verify/results.mjs` from `verify/receipts/*.json`. Each run drove the real",
  "runtime (`dist/main.mjs`, `WORKFLOW=<id>`) through the FetchSandbox managed relay against isolated",
  "twins (Stripe, HubSpot, Gmail, Google Calendar, Slack, Asana, WorkOS, GitHub, Twilio, PagerDuty, Notion, Box).",
  "Each row is a separate receipt with its own version and run ID. Unmeasured checks are not passes;",
  "a failed baseline can prevent later checks from running. These receipts do not prove native-provider deployment.",
  "",
  "| Workflow | Checks held | Violated | Unmeasured (blocked) | Verdict | Receipt |",
  "|---|---|---|---|---|---|",
];
const details = [];
for (const wf of WORKFLOWS) {
  const file = join(HERE, "receipts", `${wf}.json`);
  if (!existsSync(file)) {
    out.push(`| \`${wf}\` | — | — | — | not run | — |`);
    continue;
  }
  const r = JSON.parse(readFileSync(file, "utf8"));
  const receiptUrl = r.receipt_url?.startsWith("/") ? `https://fetchsandbox.com${r.receipt_url}` : r.receipt_url;
  const { checks: names } = await import(`./contracts/${wf}.mjs`);
  const label = Object.fromEntries(names.map((c) => [c.id, c.name]));
  const n = (s) => r.checks.filter((c) => c.status === s).length;
  out.push(`| \`${wf}\` | ${n("held")} / ${r.checks.length} | ${n("violated")} | ${n("unmeasured")} | ${r.verdict} | [${r.run_id}](${receiptUrl}) |`);
  details.push(`## \`${wf}\``, "", `App version \`${r.app_version}\` · session \`${r.session_id}\` · recorded ${r.recorded_at}`, "", "| Check | Result | Verifier note |", "|---|---|---|");
  for (const c of r.checks) details.push(`| ${label[c.id] ?? c.id} (\`${c.id}\`) | ${ICON[c.status] ?? c.status} | ${String(c.explanation ?? "").replaceAll("|", "\\|")} |`);
  details.push("");
}
out.push(
  "",
  "Read each verdict independently. Unmeasured checks may reflect missing fixtures, unsupported operations,",
  "a contract that omitted a provider, or checks not run after a failed baseline. Inspect the recorded reason;",
  "do not count them as passes. Production Calendar freeBusy is currently unsupported. Zendesk is discoverable",
  "through production MCP, but the original contracts excluded it and retain historical absence explanations.",
  "",
  ...details,
  "## FetchSandbox twin findings",
  "",
  "Historical findings recorded while building the original workflows. They are not fresh revalidation of",
  "every provider operation. Use the current per-check receipts above for measured results.",
  "",
  "| Twin | Finding | Impact here |",
  "|---|---|---|",
  "| Zendesk | Historical provider-discovery failure; production MCP now has a bounded Zendesk twin | Existing contracts still exclude Zendesk; required operations need reassessment and execution |",
  "| Gmail | `POST /gmail/v1/users/{userId}/messages/send` → 404 `Resource me not found` for `me` and for an email userId; `drafts.create` works | Workflows create drafts (also the safer design); sending is a human/control-plane step |",
  "| Stripe | `GET /v1/subscriptions?status=all` returns `[]` (filter treated as a literal status); `status=canceled` also returns `[]` | Client omits `status` (Stripe's non-canceled default) and asks for `canceled` separately; canceled detection is unproven on the twin |",
  "| Stripe | `Idempotency-Key` is not honoured: two `POST /v1/customers` with the same key create two customers | Workflows look up before create and claim each effect in their own ledger |",
  "| Stripe | New subscriptions come back `incomplete` (matches real Stripe without a payment method) | Exposed a real duplicate-subscription bug in onboarding-kickoff, now fixed and regression-tested |",
  "| Stripe | Seeded subscription items carry no `price` object (real Stripe always includes it) | Item price access is null-safe; MRR on seed data computes as 0 |",
  "| Google Calendar | `GET /calendar/v3/calendars/primary/events/{id}` → 404 `Resource primary not found` right after a successful insert | `reconcile` reports calendar effects as `unverifiable` on the twin |",
  "| Slack | `chat.postMessage` to an unknown channel returns `ok: true` unless the `channel_not_found` fault is armed | None (faults are armed explicitly in the contracts) |",
  "| HubSpot | Contacts only (no deals, notes, tasks); custom properties are rejected with `PROPERTY_DOESNT_EXIST` | Workflows use contacts with standard properties (`lifecyclestage`) |",
  "| Stripe | Quotes reject `discounts[]` (501 unsupported); quotes with mixed billing intervals are refused | Discount recorded in quote metadata; mixed-interval RFQs route to Sales |",
  "| Stripe | Invoices carry no line items; credit-note create/get returns sample amounts | Claims validated on paid amount only; credit-note amount read-back unproven |",
  "| Shopify | `POST /orders.json` 404 and order lists are empty; products are placeholder records | Not usable as ACME's order system; Stripe invoices stand in for orders |",
  "| Box | No seeded files; `/search` returns a placeholder object | Compliance-document lookup and shared links unproven |",
  "| Notion | Database query returns generic sample pages without the library's fields | Security-questionnaire answers from the library unproven |",
  "| Asana | Task lists return generic samples (create/get/update/stories work) | Repeat-supplier CAPA escalation unproven |",
  "| WorkOS | Membership list returns a generic object; `deactivate` 404; user list always returns an `after` cursor and shows users as never signed in | Mover role removal fails closed; client stops paging on no new users |",
  "| PagerDuty | Created incidents have no id; notes read-back returns sample data | Incidents arrive as webhook payloads; note write proven, read-back not |",
  "| GitHub | Listing issues by label returns `[]` (create/get/patch work) | PCN records are read by number |",
  "",
);
writeFileSync(join(HERE, "RESULTS.md"), out.join("\n") + "\n");
console.log(out.slice(0, 14).join("\n"));
